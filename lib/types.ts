import type { PopupViewState } from './popupViewState';

export interface CollectOptions { css?: boolean; icons?: boolean; inline?: boolean }
export interface RawImage {
  original?: boolean;
  source: string;
  sources?: string[];
  alt: string;
  width: number;
  height: number;
  declared: string[];
  srcsets: string[];
  link: string;
}
export interface PageCapture {
  inlineAllowed?: boolean;
  url: string;
  baseUrl: string;
  title: string;
  challenged: boolean;
  total: number;
  truncated: boolean;
  images: RawImage[];
}
export interface ImageResult {
  /** URL was found in page content, rather than generated by a conversion rule. */
  pageImage?: boolean;
  /** Discovery index for page URLs; generated matches have no page index. */
  pageOrder?: number;
  id: string;
  url: string;
  source: string;
  label: string;
  reason: string;
  candidate: boolean;
  width: number;
  height: number;
}
export interface HostedImagePage { url: string; source: string; label: string }
export interface AnalysisState {
  /** Recognized external image detail pages, resolved only after a user gesture and permission. */
  hostedPages?: HostedImagePage[];
  /** Display-only original webpage URL for imported HTML; url stays the workspace identity. */
  sourceUrl?: string;
  unresolvedCount?: number;
  job: string;
  resolverVersion?: string;
  documentId?: string;
  tabId: number;
  url: string;
  status: 'running' | 'done' | 'error';
  title?: string;
  started: number;
  message: string;
  total: number;
  truncated: boolean;
  results: ImageResult[];
  selected: string[];
  selectionMode?: SelectionMode;
  selectionFilter?: ImageFilter;
}
export type SelectionMode = 'page' | 'large' | 'small' | 'all' | 'custom';
export type ImageFilter = Exclude<SelectionMode, 'custom'>;
export type ImageView = 'grid' | 'list';
export interface DownloadJob {
  url: string;
  filename: string;
  status: 'pending' | 'starting' | 'in_progress' | 'complete' | 'failed';
  downloadId?: number;
  error?: string;
}
export interface DownloadBatch {
  id: string;
  jobs: DownloadJob[];
}
export type Request =
  | { type: 'ANALYZE'; tabId: number; mode?: SelectionMode; scroll?: boolean }
  | { type: 'SAVE_POPUP_VIEW'; tabId: number; view: PopupViewState }
  | { type: 'LOAD_POPUP_VIEW'; tabId: number; job: string }
  | { type: 'IMPORT_CAPTURE'; capture: PageCapture }
  | { type: 'HOSTED_ORIGINAL'; job: string; pageUrl: string; url: string }
  | { type: 'SELECT'; job: string; selected: string[]; mode?: SelectionMode; filter?: ImageFilter }
  | { type: 'DOWNLOAD'; job: string; selected: string[] }
  | { type: 'DOWNLOAD_ZIP'; job: string; selected: string[] }
  | { type: 'RESUME_ARCHIVE'; batchId: string }
  | { type: 'RETRY_ARCHIVE'; batchId: string }
  | { type: 'REMOVE_ARCHIVE_RECORDS'; ids: string[]; completedOnly: boolean }
  | { type: 'OPEN_ARCHIVES' }
  | { type: 'RESUME_DOWNLOADS' };

export interface ArchiveItem { id: string; url: string; kind: 'large' | 'small'; filename: string; status: 'pending' | 'complete' | 'failed'; error?: string; bytes?: number }
export interface ArchiveBatch {
  /** Display-only source metadata; pageUrl remains the task isolation key. */
  sourceUrl?: string;
  id: string; title: string; filename: string; pageUrl: string; items: ArchiveItem[];
  sourceTabId?: number;
  cacheUntil?: number;
  retryOf?: string;
  retryBatchId?: string;
  status: 'queued' | 'fetching' | 'packing' | 'saving' | 'complete' | 'partial' | 'failed' | 'cancelled';
  started: number; updated: number; bytes: number; message: string; tabId?: number; downloadId?: number;
  /** When the current task page was (re)launched. `started` stays the original task time. */
  launched?: number;
}
